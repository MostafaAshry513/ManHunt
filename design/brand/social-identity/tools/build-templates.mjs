// Writes the editable HTML/CSS post templates for the social identity kit.
//
//   node tools/build-templates.mjs
//
// Extends the motion kit: loads the shared radar art (src/art.js, built on
// motion-core.js) and inlines the official lockup SVGs verbatim. Each generated
// template is a standalone page at its exact export size; the COPY blocks are
// marked so the owner can edit a line and re-render without redrawing:
//
//   node tools/render.mjs page --file social-identity/templates/story-1080x1920.html \
//        --size 1080x1920 --out out/templates/story-1080x1920.png
import { readFile, writeFile } from 'node:fs/promises';
import vm from 'node:vm';
import path from 'node:path';

const TOOLS = import.meta.dirname;
const KIT = path.resolve(TOOLS, '..');
const BRAND = path.resolve(KIT, '..'); // design/brand
const MOTION = path.join(BRAND, 'motion-kit');

vm.runInThisContext(await readFile(path.join(MOTION, 'src', 'motion-core.js'), 'utf8'));
vm.runInThisContext(await readFile(path.join(KIT, 'src', 'art.js'), 'utf8'));
const A = globalThis.MHArt;
const C = globalThis.MHCore;

const readSvg = async (file) => (await readFile(path.join(MOTION, 'assets', 'lockup', file), 'utf8')).trim();

// Copies the owner-approved lockup SVGs into src/generated/lockup.js so every
// banner / GIF stage inlines the official vectors instead of retyping them.
//
//   node tools/sync-lockup.mjs
//
// Source of truth: design/brand/identity/final/lockup/ (LOCKUP.md §1).
// The copies in assets/lockup/ are byte-identical; this script re-reads those
// copies, verifies their SHA-256 against assets/lockup/sha256.json, and writes
// the inline markup the render stage consumes (LOCKUP.md: "inline the SVG markup
// rather than loading it as a file").
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';

const KIT = path.resolve(import.meta.dirname, '..');
const LOCK_DIR = path.join(KIT, 'assets', 'lockup');
const OUT = path.join(KIT, 'src', 'generated', 'lockup.js');

const FILES = {
  wordmark: 'wordmark-light-on-dark.svg',
  horizontal: 'lockup-horizontal-light-on-dark.svg',
  stacked: 'lockup-stacked-light-on-dark.svg',
  mark: 'mark-light-on-dark.svg',
};

const hash = (buf) => createHash('sha256').update(buf).digest('hex').toUpperCase();

function main() {
  return (async () => {
    const manifestText = (await readFile(path.join(LOCK_DIR, 'sha256.json'), 'utf8')).replace(/^\uFEFF/, '');
    const manifest = JSON.parse(manifestText);
    const byFile = new Map(manifest.map((row) => [row.File, row]));
    const out = {};
    const report = [];

    for (const [key, file] of Object.entries(FILES)) {
      const buf = await readFile(path.join(LOCK_DIR, file));
      const sha = hash(buf);
      const row = byFile.get(file);
      if (row && row.Canonical !== sha) {
        throw new Error(`lockup drifted: ${file}\n  expected ${row.Canonical}\n  actual   ${sha}`);
      }
      const svg = buf.toString('utf8').trim();
      if (/<text\b|<tspan\b|font-family/i.test(svg)) {
        throw new Error(`lockup ${file} contains text; official lockups must stay drawn paths`);
      }
      out[key] = { file, sha256: sha, svg };
      report.push({ key, file, sha256: sha, bytes: buf.length });
    }

    const banner = `/* AUTO-GENERATED by tools/sync-lockup.mjs — do not edit.
   Official ManHunt lockups, inlined verbatim from
   design/brand/identity/final/lockup/ (copies in assets/lockup/).
   Source of truth: design/brand/identity/final/LOCKUP.md
   Never retype, re-crop or letter-space the wordmark. */\n`;
    const js = `${banner}window.MH_LOCKUP_SVG = ${JSON.stringify(out, null, 2)};\n`;
    await mkdir(path.dirname(OUT), { recursive: true });
    await writeFile(OUT, js, 'utf8');

    console.log('[sync-lockup] wrote ' + path.relative(KIT, OUT));
    for (const row of report) console.log(`  ${row.key.padEnd(10)} ${row.sha256}  ${row.file} (${row.bytes} B)`);
  })();
}

main().catch((err) => { console.error(err); process.exit(1); });
